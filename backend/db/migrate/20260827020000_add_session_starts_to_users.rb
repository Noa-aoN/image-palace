# セッションが**いつ始まったか**を、端末ごとに控える。
#
# ## なぜ要るか
#
# トークンの寿命は7日だが、リクエストのたびに再発行されるので、
# 使い続けている限り**同じセッションが永久に延びる**。
# 置き忘れた端末や、持ち出されたトークンが、いつまでも有効になる。
#
# 定石は「絶対上限」を別に置くこと（何日か経ったら、使っていても必ず入り直す）。
#
# ## なぜトークンの中に持たないか
#
# devise-token-auth はトークンを更新するとき、その端末の記録を
# **まるごと差し替える**（token / expiry / updated_at だけ）。
# 中へ足した値はリクエストのたびに消える。
#
# 更新の経路は全 API が通る道なので、そこへ手を入れるのは避けたい。
# 別の列に持てば、gem の更新と関係なく残る。
#
# ## 既にログインしている人を締め出さない
#
# 記録が無い端末は「いま始まった」ものとして数える（初めて見たときに書く）。
# デプロイした瞬間に全員がログアウトする、を避ける。
class AddSessionStartsToUsers < ActiveRecord::Migration[8.1]
  def change
    add_column :users, :session_starts, :jsonb, default: {}, null: false
  end
end
