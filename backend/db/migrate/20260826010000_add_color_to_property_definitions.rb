# 項目ごとの色。**見出しの前に置く小さな丸の色**。
#
# ## なぜ役割の色では足りないか
#
# 役割（記憶要素 / 変換要素 / 管理要素）の色は既にあるが、それは3つしかない。
# 同じ役割の中に「語源」「品詞」「読み方」が並ぶと、どれも同じ色で出る。
# **自分が作った項目を、自分の物差しで見分けたい**ときに手立てが無い。
#
# ## なぜ色の名前を持つのか（`#RRGGBB` を持たない）
#
# 実際の色味は画面側の設計に属する。地がアイボリーなので、載る色は
# その地に合わせて決まっており、あとから調整もされる。
# 生の値を持つと、色を調整するたびに**保存済みの行を書き換える**ことになる。
# 名前で持てば、対応表を直すだけで全部に効く。
#
# ## 既定は無色
#
# `null` は「選んでいない」。丸を出さない。
# 全項目に色が付いていると、どれが目印なのかが分からなくなるので、
# **付けた人が付けたものだけ**が目立つ状態を既定にする。
class AddColorToPropertyDefinitions < ActiveRecord::Migration[8.1]
  def change
    add_column :property_definitions, :color, :string
  end
end
