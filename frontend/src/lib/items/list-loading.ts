/**
 * 一覧を取り直すとき、骨組み（スケルトン）に戻すか。
 *
 * **裏での取り直しでは戻さない。** 生成中のカードを追いかける取り直しでも
 * 骨組みにしていたため、1枚作っただけで**一覧ぜんぶが骨組みになり、
 * 既に出来ているカードまで消えて見えた**。
 *
 * 骨組みを出すのは、並ぶ中身そのものが入れ替わるとき
 * （頁を移る・絞り込みを変える・並び順を変える）だけでよい。
 * そのときは古い中身を見せ続けるほうが、かえって嘘になる。
 */
export function shouldShowSkeleton({
  background,
  hasItems,
}: {
  /** 生成中を追いかけるなど、利用者が起こしていない取り直しか */
  background: boolean
  /** いま画面に出ているものがあるか */
  hasItems: boolean
}): boolean {
  if (!background) return true

  // 裏の取り直しでも、まだ何も出ていなければ骨組みでよい（消すものが無い）
  return !hasItems
}
