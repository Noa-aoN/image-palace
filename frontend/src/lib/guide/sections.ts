export type GuideSlug = 'getting-started' | 'features' | 'faq' | 'glossary' | 'sitemap'

export type GuideSection = {
  slug: GuideSlug
  title: string
  excerpt: string
  icon: LucideIcon
  /**
   * 見出し画像の URL。用意できたものから足していく。
   * 無いあいだは一覧に画像の枠ごと出さない（空の枠は「読み込み中」に見える）
   */
  image?: string
}

// 一覧・詳細で共有するセクション定義（表示順）。
export const GUIDE_SECTIONS: GuideSection[] = [
  { slug: 'getting-started', title: '使い方ガイド', excerpt: '4ステップで始める、基本の流れ。', icon: Sparkles },
  { slug: 'features', title: '機能一覧', excerpt: 'つくる・ためる・つなぐ・覚える・学ぶ。テーマ別のできること。', icon: Layers },
  { slug: 'faq', title: 'よくある質問', excerpt: '生成にかかる時間・料金・データの公開範囲など。', icon: HelpCircle },
  { slug: 'glossary', title: '用語集', excerpt: 'カード・ボックス・キャンバス・スペースなど、用語の意味。', icon: BookMarked },
  { slug: 'sitemap', title: 'サイトマップ', excerpt: 'サービス内の全ページをツリーで一覧。', icon: Map },
]

export function getGuideSection(slug: string): GuideSection | undefined {
  return GUIDE_SECTIONS.find((s) => s.slug === slug)
}

