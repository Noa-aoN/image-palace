/**
 * おすすめ使用例。
 *
 * 「何ができるか」（機能一覧）ではなく、**何のために使うか**を並べる。
 * 初めての人が最初に困るのは操作ではなく、**単語帳以外の使い道が思いつかない**こと。
 *
 * **いま出来ることだけで書く。** まだ無い機能を例にすると、真似しようとして
 * 見つからず、書いてあることが信用されなくなる。
 */
